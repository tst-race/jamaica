"""Plot a chart of feature values grouped by label.
"""

import argparse
import os
import sys
import pandas as pd
from simple_term_menu import TerminalMenu
from pathlib import Path
import matplotlib.pyplot as plt
import matplotlib.lines as lines


def parse_arguments() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="""
            Plot a bar chart of feature values grouped by label. Should be run against
            one or more CSV files generated by the `stats.py` script.
        """
    )

    parser.add_argument(
        "dataset_file_name",
        help="the CSV file to analyze or a directory containing CSV files to select from",
    )
    # parser.add_argument(
    #     "--file-filter", type=str, help="filter the file names displayed for selection"
    # )
    parser.add_argument("--features", type=str, nargs="*", help="feature(s) to plot")
    parser.add_argument("--labels", type=str, nargs="*", help="label(s) to plot, e.g. flag, encrypted, length")
    # parser.add_argument(
    #     "--sort",
    #     action="store_true",
    #     help="Sort the values before plotting.",
    # )
    # parser.add_argument(
    #     "--length",
    #     action="store_true",
    #     help="Plot the length of the field instead of the value.",
    # )
    # parser.add_argument("--num-samples", type=int, help="number of samples to display")
    # parser.add_argument(
    #     "--direction",
    #     type=str,
    #     choices=["from_src", "from_dst"],
    #     help="filter the file names displayed for selection",
    # )

    return parser.parse_args()


def select_file_names(file_dir: str, file_filter: str = None) -> list[str]:
    file_filter = f"*{file_filter}" if file_filter is not None else ""
    file_names = list(Path(file_dir).rglob(f"{file_filter}*.csv"))
    field_terminal_menu = TerminalMenu(
        [os.path.basename(name) for name in file_names],
        title="Select input file(s):",
        multi_select=True,
        show_multi_select_hint=True,
        show_search_hint=True,
    )
    menu_entry_indices = field_terminal_menu.show()

    return [file_names[i] for i in menu_entry_indices]


def select_features(all_features: list[str]) -> str:
    field_terminal_menu = TerminalMenu(
        all_features,
        title="Select features to plot:",
        multi_select=True,
        show_multi_select_hint=True,
        show_search_hint=True,
    )
    menu_entry_indices = field_terminal_menu.show()

    return [all_features[i] for i in menu_entry_indices]


def main():
    args = parse_arguments()

    print(args)

    if os.path.isdir(args.dataset_file_name):
        dataset_files = select_file_names(args.dataset_file_name)
    else:
        dataset_files = [args.dataset_file_name]

    print(f"Dataset files: {dataset_files}")

    # Concatenate all the input datasets.
    X = []
    for file_name in dataset_files:
        df = pd.read_csv(file_name, sep=r"\s*,\s*", engine="python")
        # NOTE: ignore all samples labeled as IGNORE.
        df = df[~df.label.str.contains("IGNORE_")]
        X.append(df)
    X = pd.concat(X, ignore_index=True)
    # Sort by row names.
    X = X.sort_values("name")

    # If labels were provided then filter the dataset to only include them.
    if args.labels is not None:
        for label in args.labels:
            if not label in X["label"]:
                print(f"WARNING: label {label} does not exist in dataset")
        X = X.loc[X["label"].isin(args.labels)]
        if X.shape[0] == 0:
            print("ERROR: all fields were filtered out by the label argument")
            sys.exit(1)

    features = args.features
    if features is None:
        all_features = X.columns.tolist()
        features = select_features(all_features)

    # grouped_data = X.groupby(["label", "name"])
    grouped_data = X.groupby("label")

    labels = grouped_data.groups.keys()
    bar_width = 0.1  # TODO: scale down based on number of samples.
    fig, axs = plt.subplots(len(features), 1)
    fig.suptitle([str(name) for name in dataset_files], fontsize=16)
    for plot_index, feature in enumerate(features):
        ax = axs[plot_index] if len(features) > 1 else axs
        for index, (label, group) in enumerate(grouped_data):
            x = [index + (j * bar_width) for j in range(len(group))]
            ax.bar(x, group[feature], bar_width, label=label)

            # if True:
            # Write the row name on each bar.
            previous_name: str = ""
            for j, name in enumerate(group["name"]):
                ax.text(x[j], 0.05, name, ha="center", va="bottom", rotation="vertical")
                if previous_name and name != previous_name:
                    # ax.axvline(x=(x[j] - (bar_width / 2)), ymax=0.5)
                    x_position = x[j] - (bar_width / 2)
                    line_height = group[feature].iloc[j]
                    ax.add_line(
                        lines.Line2D([x_position, x_position], [0, line_height])
                    )
                previous_name = name

        # quit()
        ax.set_xlabel("Field Type")
        ax.set_ylabel(feature)
        # ax.set_title(feature)
        ax.set_xticks([i + bar_width for i in range(len(labels))])
        ax.set_xticklabels(labels)

        # TODO: hide behind CLI flag
        # ax.set_yscale('log')

        ax.legend()
    plt.show()


if __name__ == "__main__":
    main()
